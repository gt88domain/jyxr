import assert from 'node:assert/strict';
import {createHarness} from './ui-harness.mjs';

const h=await createHarness('creation-smoke');
const {page,output,report,pass,ready,visible,click,state,continueDialogue,noOverflow}=h;
let failure;
try{
  await page.goto(report.baseURL,{waitUntil:'networkidle'});
  await visible('[data-action="new"]');
  await click('[data-action="new"]');
  await page.locator('#hero-name').fill('问答测试侠');
  await page.locator('#character-form button[type="submit"]').click();
  await ready();
  await page.setViewportSize({width:375,height:812});
  await noOverflow('original creation questions at 375px');
  await click('[data-action="creation-answer"][data-index="1"]');
  await click('[data-action="creation-back"]');
  assert.equal((await state()).creation.questionIndex,0);
  for(let q=0;q<7;q++) await click(`[data-action="creation-answer"][data-question="${q}"][data-index="${q===6?4:0}"]`);
  assert.equal(await page.locator('[data-action="creation-portrait"]').count(),24);
  await noOverflow('24 original portrait choices at 375px');
  await page.screenshot({path:output+'creation-portraits-mobile.png',fullPage:true});
  await click('[data-action="creation-portrait"][data-id="头像.独孤求败"]');
  const draft=(await state()).creation;
  assert.equal(draft.preview.silver,6100);
  assert.equal(draft.preview.internalSkills.find(s=>s.id==='基本内功').level,20);
  assert.equal(draft.preview.items.find(i=>i.id==='松果').quantity,3);
  await noOverflow('original creation preview at 375px');
  await page.screenshot({path:output+'creation-preview-mobile.png',fullPage:true});
  for(let n=0;n<3;n++) await click('[data-action="creation-roll"]');
  const rolled=(await state()).creation;
  assert.deepEqual(rolled.preview.items,draft.preview.items);
  assert.equal(rolled.preview.silver,6100);
  assert.equal(Object.values(rolled.preview.randomBonus).reduce((sum,n)=>sum+n,0),40);
  await page.setViewportSize({width:1440,height:900});
  await noOverflow('original creation preview at desktop');
  await page.screenshot({path:output+'creation-preview-desktop.png',fullPage:true});
  pass('seven original questions, backtracking, 24 portraits, authentic merchant rewards and non-accumulating rerolls');
  await click('[data-action="creation-confirm"]');
  await continueDialogue();
  const actual=await state();
  assert.equal(actual.creation,null);
  assert.equal(actual.silver,6100);
  assert.equal(actual.hero.portrait,rolled.preview.portrait);
  for(const s of rolled.preview.attributes) assert.equal(actual.hero.attributes.find(a=>a.id===s.id).baseValue,s.value);
  await click('[data-action="save"]');
  await page.waitForFunction(()=>document.querySelector('#toast')?.textContent==='当前世界的进度已保存。');
  await page.reload({waitUntil:'networkidle'});
  await visible('[data-action="load"]');
  await click('[data-action="load"]');
  const loaded=await state();
  assert.deepEqual(loaded.hero,actual.hero);
  assert.deepEqual(loaded.inventory,actual.inventory);
  assert.equal(loaded.silver,6100);
  pass('confirmed attributes, original inventory, portrait and level20 internal art survive browser save/reload');
}catch(e){failure=e;}
await h.finish(failure);
