import assert from 'node:assert/strict';
import {createHarness} from './ui-harness.mjs';

const h = await createHarness('original-world-smoke');
const {page, output, report, pass, ready, visible, click, state, continueDialogue, noOverflow} = h;
async function location(id) {
  if (await page.locator('#destination-search').count()) await page.locator('#destination-search').fill(id);
  await click(`[data-action="interact"][data-id="${id}"]`);
}
async function choice(index) {await click(`[data-action="choice"][data-index="${index}"]`); await continueDialogue();}
let failure;
try {
  await page.goto(report.baseURL, {waitUntil: 'networkidle'});
  await visible('[data-action="new"]');
  await page.locator('#import-file').setInputFiles(`${output}exported-save.json`);
  await page.waitForFunction(() => document.querySelector('#toast')?.textContent === '存档已导入。');
  await ready();
  await location('南贤居');
  await location('南贤');
  await continueDialogue();
  await choice(0);
  await choice(0);
  const started = await state();
  assert.equal(started.map.kind, 'large');
  assert.equal(started.tutorial.id, '购买物品');
  assert.equal(started.silver, 310);
  await page.setViewportSize({width:375,height:812});
  await page.locator('#destination-search').fill('洛阳');
  assert.equal(await page.locator('[data-action="interact"][data-id="洛阳"]').isVisible(), true);
  await noOverflow('original world travel and destination search at 375px');
  await page.screenshot({path:`${output}original-world-mobile.png`,fullPage:true});
  await page.setViewportSize({width:1440,height:900});
  const days = started.adventure.days;
  await location('洛阳');
  assert.ok((await state()).adventure.days > days, 'Real map distance must consume time');
  await location('商店');
  await continueDialogue();
  await choice(0);
  const gifts = await state();
  assert.equal(gifts.tutorial.id,'购买药品完成');
  assert.equal(gifts.inventory.find(i=>i.id==='小还丹').count,(started.inventory.find(i=>i.id==='小还丹')?.count||0)+5);
  pass('original map travel, original 300 silver and newbie.xml gift completion');
  await location('返回');
  await location('南贤居');
  const before = await state();
  await location('南贤');
  await continueDialogue();
  assert.equal((await state()).hero.maxHp,before.hero.maxHp+100);
  assert.equal((await state()).hero.maxMp,before.hero.maxMp+100);
  await choice(0);
  assert.equal((await state()).tutorial.id,'教训小孩');
  await location('返回');
  await location('洛阳');
  await location('小孩');
  await continueDialogue();
  await visible('.duel-screen');
  assert.equal((await state()).battle.id,'新手任务小孩');
  await click('[data-action="battle-speed"][data-id="4"]');
  await click('[data-action="battle-mode"][data-id="auto"]');
  await page.locator('[data-action="leave-battle"]').waitFor({state:'visible',timeout:180000});
  const fought = await state();
  assert.ok(['win','lose'].includes(fought.battle.outcome));
  assert.ok(fought.battle.events.some(e=>e.kind==='Damaged'&&e.amount>0));
  await click('[data-action="leave-battle"]');
  await continueDialogue();
  assert.equal((await state()).tutorial.id,'教训小孩完成');
  await location('返回');
  await location('南贤居');
  await location('南贤');
  await continueDialogue();
  assert.equal((await state()).phase,'sect');
  const sects=(await state()).sects;
  assert.equal(sects.length,9);
  assert.ok(sects.every(s=>s.available));
  await page.screenshot({path:`${output}original-sects-desktop.png`,fullPage:true});
  await page.setViewportSize({width:375,height:812});
  await noOverflow('all nine original sect entries at 375px');
  await page.screenshot({path:`${output}original-sects-mobile.png`,fullPage:true});
  await page.setViewportSize({width:1440,height:900});
  pass('full original tutorial reaches real nine-sect selection after actual combat');
  await click('[data-action="select-sect"][data-id="少林派"]');
  await continueDialogue();
  await choice(0);
  const shaved=await state();
  assert.equal(shaved.phase,'world');
  assert.equal(shaved.map.id,'少林寺内');
  assert.equal(shaved.adventure.sect,'少林寺');
  assert.ok(shaved.hero.talents.some(t=>t.id==='无相'));
  assert.equal(shaved.tutorial,null);
  await click('[data-action="save"]');
  await page.waitForFunction(()=>document.querySelector('#toast')?.textContent==='当前世界的进度已保存。');
  await page.reload({waitUntil:'networkidle'});
  await visible('[data-action="load"]');
  await click('[data-action="load"]');
  assert.equal((await state()).map.id,'少林寺内');
  assert.equal((await state()).adventure.sect,'少林寺');
  await page.screenshot({path:`${output}original-shaolin-restored.png`,fullPage:true});
  pass('original Shaolin post-choice actions, real reward/map and saved sect persist');
} catch(error) {failure=error;}
await h.finish(failure);
