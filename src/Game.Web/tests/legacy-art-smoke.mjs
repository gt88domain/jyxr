import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createHarness} from './ui-harness.mjs';

const h = await createHarness('legacy-art-smoke');
const {page,output,report,pass,ready,visible,click,state,continueDialogue,closeModal,noOverflow}=h;
const hash=b=>createHash('sha256').update(b).digest('hex');
let failure;
try {
  await page.goto(report.baseURL,{waitUntil:'networkidle'});
  await visible('[data-action="new"]');
  assert.match(await page.locator('.title-footer').innerText(),/原版素材/);
  assert.match(await page.locator('#app').evaluate(e=>getComputedStyle(e).backgroundImage),/art\/legacy\//);
  await page.locator('#import-file').setInputFiles(`${output}exported-save.json`);
  await page.waitForFunction(()=>document.querySelector('#toast')?.textContent==='存档已导入。');
  await ready();
  const s=await state();
  assert.equal(s.pack.artSource.kind,'legacy');
  assert.match(s.hero.portrait,/^art\/legacy\//);
  await click('[data-action="inventory"]');
  const book=page.locator('[data-item-id="内功入门"] img');
  await book.waitFor({state:'visible'});
  assert.match(await book.getAttribute('src'),/art\/legacy\//);
  await page.waitForFunction(()=>[...document.querySelectorAll('#game-modal img')].every(e=>e.complete&&e.naturalWidth>0));
  await page.screenshot({path:`${output}original-items-desktop.png`,fullPage:true});
  await closeModal();
  pass('original title/map, character portrait and real book icon load through the modern UI');
  await click('[data-action="training"]');
  await continueDialogue();
  await visible('.duel-screen');
  const b=(await state()).battle;
  assert.match(b.background,/^art\/legacy\//);
  for(const unit of b.units) {
    assert.ok(unit.animation,'Original hero and wood dummy must use original animation atlases');
    assert.ok(unit.animation.clips.stand.frames.length>1);
    assert.match(unit.animation.texture,/^art\/legacy\//);
  }
  const canvas=page.locator('#board-viewport canvas');
  await canvas.waitFor({state:'visible'});
  await page.waitForFunction(()=>JSON.parse(document.querySelector('#board-viewport')?.dataset.animationActions||'[]').includes('stand'));
  await page.mouse.move(1,1);
  const first=await canvas.screenshot();
  await page.waitForTimeout(230);
  const second=await canvas.screenshot();
  assert.notEqual(hash(first),hash(second),'Original idle animation must actually advance its frames');
  await click('[data-action="battle-pause"]');
  const paused=await canvas.screenshot();
  await page.waitForTimeout(230);
  assert.equal(hash(paused),hash(await canvas.screenshot()),'Pause must stop the original animation frames');
  await page.screenshot({path:`${output}original-battle-paused.png`,fullPage:true});
  await click('[data-action="battle-pause"]');
  pass('original standing frames animate and pause without advancing game rules');
  const point=b.reachable.find(p=>p.x===3&&p.y===2)||b.reachable.find(p=>p.x!==2||p.y!==2);
  assert.ok(point);
  const geometry=JSON.parse(await page.locator('#board-viewport').getAttribute('data-board-geometry'));
  const bounds=await canvas.boundingBox();
  await page.mouse.click(bounds.x+geometry.left+(point.x+.5)*geometry.cell,bounds.y+geometry.top+(point.y+.5)*geometry.cell);
  await ready();
  assert.ok(JSON.parse(await page.locator('#board-viewport').getAttribute('data-animation-actions')).includes('move'));
  await click('[data-action="battle-speed"][data-id="4"]');
  await click('[data-action="battle-mode"][data-id="auto"]');
  await page.locator('[data-action="leave-battle"]').waitFor({state:'visible',timeout:180000});
  const actions=JSON.parse(await page.locator('#board-viewport').getAttribute('data-animation-actions'));
  assert.ok(actions.includes('attack'),'Actual skill facts must trigger original attack animation');
  assert.equal((await state()).battle.outcome,'win');
  pass('real movement and attacks drive original animation and settle through the shared C# engine');
  await noOverflow('original art battle at desktop');
}catch(error){failure=error;}
await h.finish(failure);
