"""Generate the TS request union from the same contract embedded by .NET."""
import argparse
import json
from pathlib import Path
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
web=Path(__file__).resolve().parents[1]
contract=json.loads((web/'contracts/commands.json').read_text())
types={'string':'string','boolean':'boolean','integer':'number','id':'number','strings':'string[]'}
lines=['// Generated by scripts/generate-contract.py; edit contracts/commands.json.','export type GameCommand =']
for name,command in contract['commands'].items():
    fields=['type: '+json.dumps(name)]+[field+': '+types[kind] for field,kind in command['fields'].items()]
    lines.append('  | {'+'; '.join(fields)+'}')
lines[-1]+=';'
lines.append('export const commandDefinitions = '+json.dumps(contract['commands'],ensure_ascii=False,separators=(',',':'))+' as const;')
text='\n'.join(lines)+'\n';output=web/'src/commands.generated.ts'
if args.check:
    if not output.exists() or output.read_text()!=text:raise SystemExit('Command contract output is stale; run npm run contract')
else:output.write_text(text)
print('Validated '+str(len(contract['commands']))+' shared command shapes' if args.check else 'Generated '+str(len(contract['commands']))+' typed command shapes')
